"""Build a D1 seed from an OFAC snapshot.

Downloads OFAC's consolidated list into a local SQLite snapshot, then emits
everything the live D1 database needs:

  snapshot.db  the raw local snapshot (gitignored, the source of truth)
  schema.sql   DDL from db.SERVING_SCHEMA_SQL
  seed.sql     every serving-table row as literal SQL
  counts.json  per-table counts, verified against D1 before a swap

The live database holds no raw entities/countries/programs/lists data. All five
endpoints are precomputed by db.precompute() and served by primary-key lookup,
so a full seed is ~800 rows against D1's 100,000 rows/day free cap — small
enough to seed in a single UTC day, with no day-separation guard.

Escaping matters: 45 of the 182 country payloads contain an apostrophe, so
every emitted literal goes through sql_quote().
"""

import json
import os
import sqlite3
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import db
import fetch

# D1 rejects any single SQL statement over 100,000 bytes. The largest real
# payload is ~7.4 KB, so this is a wide margin, but a runaway payload should
# fail the build rather than the reseed.
MAX_PAYLOAD_BYTES = 90_000


def sql_quote(value):
    """Render a Python value as a SQLite string literal.

    SQLite single-quoted literals have no backslash escape processing, so
    doubling the apostrophe is the complete escape. 45 of the 182 real country
    payloads contain one (GAMA'A AL-ISLAMIYYA), so this is load-bearing.
    """
    return "'" + str(value).replace("'", "''") + "'"


def _insert(table, columns, values, numeric=()):
    """Build one INSERT. Columns named in `numeric` are emitted unquoted.

    Deciding per column rather than per value matters: meta.value is a TEXT
    column holding what look like integers, while country_totals.total is an
    INTEGER column.
    """
    vals = ", ".join(
        str(v) if col in numeric else sql_quote(v)
        for col, v in zip(columns, values))
    return f"INSERT INTO {table} ({', '.join(columns)}) VALUES ({vals});"


def _seed_statements(data):
    out = [f"-- {len(data['country_detail'])} countries, generated by db.precompute()"]
    for key, value in data["meta"].items():
        out.append(_insert("meta", ["key", "value"], [key, value]))
    for row in data["country_totals"]:
        out.append(_insert(
            "country_totals",
            ["country", "total", "individuals", "organizations", "vessels"],
            [row["country"], row["total"], row["individuals"],
             row["organizations"], row["vessels"]],
            numeric={"total", "individuals", "organizations", "vessels"}))
    for row in data["country_detail"]:
        out.append(_insert("country_detail", ["country", "payload"],
                           [row["country"], row["payload"]]))
    for row in data["program_counts"]:
        out.append(_insert("program_counts", ["program", "n"],
                           [row["program"], row["n"]], numeric={"n"}))
    for row in data["list_counts"]:
        out.append(_insert("list_counts", ["list_name", "n"],
                           [row["list_name"], row["n"]], numeric={"n"}))
    return out


def emit_seed(seed_dir):
    """Compute the serving tables from seed/snapshot.db and write the seed files.

    Returns the counts dict written to counts.json.
    """
    snapshot = os.path.join(seed_dir, "snapshot.db")
    conn = sqlite3.connect(f"file:{snapshot}?mode=ro", uri=True)
    conn.row_factory = sqlite3.Row
    try:
        data = db.precompute(conn)
    finally:
        conn.close()

    for row in data["country_detail"]:
        size = len(row["payload"].encode("utf-8"))
        if size > MAX_PAYLOAD_BYTES:
            raise SystemExit(
                f"payload for {row['country']!r} is {size:,} bytes, over the "
                f"{MAX_PAYLOAD_BYTES:,} budget — D1 rejects statements over 100,000"
            )

    counts = dict(data["meta"])
    counts.pop("data_as_of", None)
    counts.update({
        "country_detail": len(data["country_detail"]),
        "country_totals": len(data["country_totals"]),
        "program_counts": len(data["program_counts"]),
        "list_counts": len(data["list_counts"]),
        # Row counts alone pass for a country_detail full of garbage — every row
        # present, every row wrong. The swap compares this against the database
        # so a truncated or empty payload fails before anything is deployed.
        "country_detail_bytes": sum(
            len(r["payload"].encode("utf-8")) for r in data["country_detail"]),
    })

    os.makedirs(seed_dir, exist_ok=True)
    with open(os.path.join(seed_dir, "schema.sql"), "w") as fh:
        fh.write(db.SERVING_SCHEMA_SQL)
    with open(os.path.join(seed_dir, "seed.sql"), "w") as fh:
        fh.write("\n".join(_seed_statements(data)) + "\n")
    with open(os.path.join(seed_dir, "counts.json"), "w") as fh:
        json.dump(counts, fh)

    return counts


def main(out_dir):
    os.makedirs(out_dir, exist_ok=True)
    snapshot = os.path.join(out_dir, "snapshot.db")
    if os.path.exists(snapshot):
        os.unlink(snapshot)

    print("downloading + parsing OFAC snapshot ...", flush=True)
    fetch.load_data(snapshot)

    counts = emit_seed(out_dir)
    print("seed files written to", out_dir, "counts:", counts, flush=True)
    return counts


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "seed")